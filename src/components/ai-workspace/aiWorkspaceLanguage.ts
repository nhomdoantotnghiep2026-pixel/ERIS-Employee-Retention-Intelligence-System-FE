export function useAiTr() {
  const { language, t } = useLanguage()
  return useCallback((copy: string, values?: Record<string, string | number>) => {
    const translated = language === "vi" ? copy : english[copy] ?? t(copy)
    return translated.replace(/\{([a-zA-Z][a-zA-Z0-9_]*)\}/g, (token, name: string) => values?.[name] === undefined ? token : String(values[name]))
  }, [language, t])
}
